import streamlit as st
import os

# --- 1. إعداد واجهة البرنامج ---
st.set_page_config(page_title="برنامج حَسْم - تحليل الحوادث", page_icon="🚓", layout="centered")
st.title("🚓 برنامج حَسْم")
st.subheader("نظام تحليل الحوادث المرورية المدعوم بالذكاء الاصطناعي")

st.success("✅ تم ربط النظام بنجاح (نظام الإدخال المفصل: نوع الطريق، مركبة 1، مركبة 2)")

# --- 2. تهيئة حالة الجلسة (Session State) ---
if 'report_ready' not in st.session_state:
    st.session_state['report_ready'] = False

# دالة لمسح الحقول والتقرير بالكامل
def clear_inputs():
    st.session_state['report_ready'] = False

# --- 3. واجهة الإدخال المفصلة (نوع الطريق والمركبات) ---
st.markdown("---")
st.markdown("### 📋 إدخال تفاصيل أطراف الحادث والطريق")

road_type = st.selectbox(
    "🛣️ نوع الطريق / الموقع:",
    [
        "اختر نوع الطريق...",
        "دوار",
        "تقاطع",
        "طريق عام (مسارات متعددة)",
        "شارع فرعي / مواقف"
    ]
)

veh1_desc = st.text_input("🚗 تفاصيل المركبة الأولى (الأولى / المتضررة)", placeholder="مثال: تسير بشكل نظامي في مسارها الأوسط")
veh2_desc = st.text_input("🚙 تفاصيل المركبة الثانية (الثانية / المتسببة)", placeholder="مثال: انحرفت بشكل مفاجئ / رجعت للخلف / صدمت من الخلف")

# توزيع الأزرار (بدء التحليل ومسح)
col1, col2 = st.columns([3, 1])
with col1:
    analyze_btn = st.button("🔍 بدء تحليل الحادث بالذكاء الاصطناعي", use_container_width=True)
with col2:
    clear_btn = st.button("🗑️ مسح", on_click=clear_inputs, use_container_width=True)

if analyze_btn:
    if road_type == "اختر نوع الطريق..." or not veh1_desc or not veh2_desc:
        st.warning("⚠️ الرجاء اختيار نوع الطريق وتعبئة تفاصيل المركبتين بدقة أولاً")
    else:
        with st.spinner("⏳ جاري فحص الحادث وتحديد نسب المسؤولية..."):
            
            combined_text = f"الطريق: {road_type} | المركبة 1: {veh1_desc} | المركبة 2: {veh2_desc}"
            combined_lower = combined_text.lower()
            
            # تحديد النسب والسيناريوهات بناءً على المعطيات المدخلة
            if "رجوع" in combined_lower or "للخلف" in combined_lower:
                error_percentage = "100% على المركبة التي قامت بالرجوع للخلف"
                tech_analysis = f"""
1. **وضعية المركبات:** المركبة الأولى ({veh1_desc})، بينما قامت المركبة الثانية ({veh2_desc}).
2. **حركة المركبة المتسببة:** قامت بالتحرك للخلف دون التأكد التام من خلو الطريق.
3. **نقطة الاصطدام:** تركزت التلفيات بين مؤخرة المركبة المرتجعة ومقدمة أو جانب المركبة الأخرى.
                """
                legal_qualification = """
وفقاً لنظام المرور ولائحته التنفيذية بشأن قواعد الرجوع للخلف:
* مسؤولية السائق الذي يرجع للخلف عن كافة الأضرار الناتجة لعدم التأكد من خلو الطريق.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث رجوع للخلف.

**نوع الطريق:** {road_type}
* **المركبة الأولى:** {veh1_desc}
* **المركبة الثانية:** {veh2_desc}

**التحليل الفني والقانوني:** تبين من المعطيات أن المركبة المتسببة قامت بالرجوع للخلف واصطدمت بالمركبة الأخرى الواقفة أو السائرة بوضع نظامي. وحق الأولوية يكفل عدم تحمل الطرف المتضرر أي مسؤولية.

**النتيجة النهائية:**
* **نسبة الخطأ والمسؤولية:** 100% على قائد المركبة التي قامت بالرجوع للخلف.
* **السند النظامي:** مخالفة قواعد الرجوع للخلف وعدم التأكد من خلو الطريق.
                """
            elif "انحراف" in combined_lower or "مسار" in combined_lower or "تغيير" in combined_lower:
                error_percentage = "75% على الطرف المتسبب بالانحراف و 25% على الطرف الآخر"
                tech_analysis = f"""
1. **وضعية المركبات:** المركبة الأولى ({veh1_desc}) والمركبة الثانية ({veh2_desc}).
2. **حركة المركبة المتسببة:** انحرفت وغيرت مسارها بشكل غير آمن دون التأكد من خلو الطريق.
3. **نقطة الاصطدام:** تركزت التلفيات في الأجزاء الجانبية نتيجة التداخل المروري.
                """
                legal_qualification = """
وفقاً لنظام المرور ولائحته التنفيذية بشأن قواعد الانتقال بين المسارات:
* عدم التأكد من خلو الطريق قبل الانحراف أو تغيير المسار.
* المسؤولية المشتركة بنسب متفاوتة عند عدم انتباه الطرف الآخر بالقدر الكافي.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث انحراف وتغيير مسار.

**نوع الطريق:** {road_type}
* **المركبة الأولى:** {veh1_desc}
* **المركبة الثانية:** {veh2_desc}

**التحليل الفني والقانوني:** تبين حصول انحراف غير آمن أدى إلى التداخل والاصطدام. وحيث تقضي القواعد بتحمل المتسبب بالانحراف النسبة الكبرى، مع رصد نسبة جزئية لعدم الانتباه للطرف الآخر.

**النتيجة النهائية:**
* **نسبة الخطأ والمسؤولية:** 75% على المتسبب بالانحراف، و 25% على الطرف الثاني.
* **السند النظامي:** مخالفة قواعد الانتقال بين المسارات.
                """
            elif road_type == "دوار":
                error_percentage = "100% على المركبة الداخلة للدوار"
                tech_analysis = f"""
1. **وضعية المركبات:** المركبة الأولى ({veh1_desc}) داخل الدوار، والمركبة الثانية ({veh2_desc}) في حالة دخول.
2. **حركة المركبة المتسببة:** عدم إعطاء الأولوية لمن هم بداخل المسار الدائري.
3. **نقطة الاصطدام:** الجانب الأيسر للمركبة المستقرة ومقدمة المركبة الداخلة.
                """
                legal_qualification = """
وفقاً للائحة التنفيذية لنظام المرور:
* عدم إعطاء الأولوية للمركبات التي تسير داخل الدوار.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث تقاطع (دوار).

**نوع الطريق:** {road_type}
* **المركبة الأولى:** {veh1_desc}
* **المركبة الثانية:** {veh2_desc}

**التحليل الفني والقانوني:** الأولوية النظامية المطلقة لمن بداخل الدوار، ودخول أي مركبة دون التأكد من الخلو يعرضها لكامل المسؤولية.

**النتيجة النهائية:**
* **نسبة الخطأ والمسؤولية:** 100% على قائد المركبة الداخلة للدوار.
* **السند النظامي:** مخالفة قواعد السير داخل الدوائر.
                """
            elif road_type == "تقاطع" or "مشترك" in combined_lower:
                error_percentage = "50% على كل طرف (خطأ مشترك)"
                tech_analysis = f"""
1. **وضعية المركبات:** المركبة الأولى ({veh1_desc}) والمركبة الثانية ({veh2_desc}).
2. **حركة المركبات:** وصول المركبتين إلى نقطة تقاطع في نفس الوقت دون إعطاء أولوية متبادلة.
3. **نقطة الاصطدام:** اصطدام مباشر بين مقدمة أو جوانب المركبتين.
                """
                legal_qualification = """
وفقاً للقواعد العامة لأولويات المرور والتقاطعات:
* المسؤولية المناصفة (50% لكل طرف) لعدم التزام كل قائد بحق الأولوية والحيطة.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث تقاطع بمسؤولية مشتركة.

**نوع الطريق:** {road_type}
* **المركبة الأولى:** {veh1_desc}
* **المركبة الثانية:** {veh2_desc}

**التحليل الفني والقانوني:** التقاء مسار الطرفين دون إعطاء الأولوية النظامية أو تأكيد خلو الطريق، مما يجعل المسؤولية موزعة مناصفة.

**النتيجة النهائية:**
* **نسبة الخطأ والمسؤولية:** 50% على الطرف الأول و 50% على الطرف الثاني.
* **السند النظامي:** قواعد الأولويات المشتركة.
                """
            else:
                error_percentage = "100% على الطرف الثاني (اللاحق أو المتسبب المباشر)"
                tech_analysis = f"""
1. **وضعية المركبات:** المركبة الأولى ({veh1_desc})، والمركبة الثانية ({veh2_desc}).
2. **حركة المركبة:** عدم ترك مسافة أمان كافية أو عدم السيطرة وتوقع المفاجآت.
                """
                legal_qualification = """
وفقاً للمذكرة الإيضاحية لنظام المرور:
* عدم ترك مسافة أمان كافية أو عدم السيطرة.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث مروري نظامي.

**نوع الطريق:** {road_type}
* **المركبة الأولى:** {veh1_desc}
* **المركبة الثانية:** {veh2_desc}

**التحليل الفني والقانوني:** دراسة المعطيات وتطبيق المواد النظامية ذات العلاقة لتحديد المسؤولية الكاملة على الطرف المتسبب.

**النتيجة النهائية:**
* **نسبة الخطأ والمسؤولية:** 100% على الطرف المتسبب.
* **السند النظامي:** نظام المرور السعودي.
                """

            st.session_state['report_ready'] = True
            st.session_state['error_percentage'] = error_percentage
            st.session_state['tech_analysis'] = tech_analysis
            st.session_state['legal_qualification'] = legal_qualification
            st.session_state['official_report'] = official_report

# عرض التقرير إذا كان جاهزاً
if st.session_state.get('report_ready', False):
    st.markdown("---")
    st.markdown("### 📋 التقرير النظامي المفصل للحادث")
    
    st.markdown("---")
    st.markdown("### أولاً: التحليل الفني للحادث")
    st.markdown(st.session_state['tech_analysis'])
    
    st.markdown("---")
    st.markdown("### ثانياً: التكييف النظامي (المخالفة)")
    st.markdown(st.session_state['legal_qualification'])
    
    st.markdown("---")
    st.markdown("### ثالثاً: تقرير الحادث (بصياغة رسمية)")
    st.markdown(st.session_state['official_report'])
    
    st.markdown(f"**📌 نسبة الخطأ المعتمدة في النظام:** {st.session_state['error_percentage']}")

    st.markdown("---")
    print_html = f"""
    <script>
    function printReport() {{
        window.print();
    }}
    </script>
    <button onclick="printReport()" style="
        background-color: #ff4b4b;
        color: white;
        padding: 12px 20px;
        border: none;
        border-radius: 8px;
        font-size: 16px;
        font-weight: bold;
        cursor: pointer;
        width: 100%;">
        🖨️ طباعة التقرير / حفظ كـ PDF
    </button>
    """
    st.components.v1.html(print_html, height=60)
