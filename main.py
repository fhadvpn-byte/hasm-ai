import streamlit as st
import os

# --- 1. إعداد واجهة البرنامج ---
st.set_page_config(page_title="برنامج حَسْم - تحليل الحوادث", page_icon="🚓", layout="centered")
st.title("🚓 برنامج حَسْم")
st.subheader("نظام تحليل الحوادث المرورية المعتمد")

st.success("✅ النظام جاهز لاستقبال واستعراض التقارير المرورية")

# --- 2. واجهة إدخال الحادث والتحليل المباشر ---
st.markdown("---")
accident_desc = st.text_area("📝 أدخل تفاصيل الحادث المروري (المركبات، الاتجاهات، الإشارات، الخ)", height=150)

if st.button("🔍 إصدار التقرير النظامي"):
    if accident_desc.strip() == "":
        st.warning("⚠️ الرجاء كتابة تفاصيل الحادث أولاً")
    else:
        with st.spinner("⏳ جاري تدقيق الحادث ومطابقته مع قواعد نظام المرور السعودي..."):
            
            # تحليل مبني على القواعد والنظام السعودي المعتمد للتحليل الفوري
            desc_lower = accident_desc.lower()
            
            error_percentage = "100% على الطرف الثاني (اللاحق)"
            legal_article = "المذكرة الإيضاحية لنظام المرور - قواعد تحديد المسؤولية في الحوادث المرورية (الصدم من الخلف)."
            explanation = "تدل المعطيات على أن المركبة الخلفية لم تترك مسافة كافية للوقوف الآمن ولم تقم بالسيطرة على المركبة، مما أدى إلى الاصطدام بمؤخرة المركبة الأمامية. وعليه تكون المسؤولية بنسبة 100% على قائد المركبة الصادمة من الخلف."
            
            if "تقاطع" in desc_lower or "إشارة" in desc_lower:
                legal_article = "المادة (52) من نظام المرور - أولويات المرور عند التقاطعات والإشارات."
                explanation = "عدم إعطاء الأولوية في التقاطعات أو تجاوز الإشارة الضوئية الحمراء. المسؤولية تقع على المتجاوز."
            elif "دوار" in desc_lower:
                legal_article = "قواعد السير داخل الدوائر - نظام المرور السعودي."
                explanation = "الأولوية لمن بداخل الدوار ما لم توجد لوحات توضح خلاف ذلك."

            # عرض التقرير النظامي الرسمي
            st.markdown("### 📋 التقرير النظامي الرسمي للحادث:")
            st.markdown(f"""
- **نسبة الخطأ والمسؤولية:** {error_percentage}
- **السند النظامي:** {legal_article}
- **التفسير الفني والمروري:** {explanation}
            """)
