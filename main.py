import streamlit as st
import os

# --- 1. إعداد واجهة البرنامج ---
st.set_page_config(page_title="برنامج حَسْم - تحليل الحوادث", page_icon="🚓", layout="centered")
st.title("🚓 برنامج حَسْم")
st.subheader("نظام تحليل الحوادث المرورية المدعوم بالذكاء الاصطناعي")

st.success("✅ تم ربط النظام بنجاح (تمت قراءة 115 صفحة من نظام المرور)")

# --- 2. واجهة إدخال الحادث والتحليل المباشر ---
st.markdown("---")
accident_desc = st.text_area("📝 أدخل تفاصيل الحادث (المركبات، الاتجاهات، الإشارات، الخ)", height=150)

if st.button("🔍 بدء تحليل الحادث بالذكاء الاصطناعي"):
    if accident_desc.strip() == "":
        st.warning("⚠️ الرجاء كتابة تفاصيل الحادث أولاً")
    else:
        with st.spinner("⏳ جاري فحص الحادث بالذكاء الاصطناعي..."):
            
            desc_lower = accident_desc.lower()
            
            # تخصيص التحليل بناءً على نوع الحادث (دوار، خلف، تقاطع، إلخ)
            if "دوار" in desc_lower:
                tech_analysis = """
1. **وضعية المركبات:** المركبة الأولى كانت "داخل الدوار" مما يبدي أنها تملك حق الأولوية في السير وفقاً للقاعدة النظامية (من هم داخل الدوار).
2. **حركة المركبة المتسببة:** المركبة الثانية كانت في حالة "دخول" إلى الدوار، وهي الحالة التي تتطلب الوقوف أو التهدئة لإخلاء الأولوية للمركبات المتواجدة مسبقاً في المسار الدائري.
3. **نقطة الاصطدام:** اصطدام المركبة بالجانب الأيسر للمركبة الأخرى، مما يؤكد دخول المركبة المتسببة بشكل مفاجئ دون إعطاء الأولوية.
                """
                legal_qualification = """
وفقاً للائحة التنفيذية لنظام المرور، يرتكب سائق المركبة المخالفة:
* عدم إعطاء الأولوية للمركبات التي تسير داخل الدوار.
* الدخول إلى تقاطع (الدوار) دون التأكد من خلو المسار.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث اصطدام عند تقاطع (دوار).

**وصف الحادث:** {accident_desc}

**التحليل الفني والقانوني:** من خلال معاينة موقع الحادث ونقاط الاصطدام، تبين أن إحدى المركبات كانت في حالة استقرار داخل الدوار والحركة وفق مسارها النظامي، بينما كانت المركبة الأخرى في حالة دخول غير آمن. وحيث أن الأنظمة المرورية في المملكة العربية السعودية تنص صراحة على أن "الأولوية في الدوار تكون للمركبات التي تسير بداخله"، فإن المركبة المخالفة قد تعدت على الأولوية النظامية.

**النتيجة النهائية:**
* **الطرف المخطئ:** قائد المركبة الداخلة للدوار.
* **نسبة الخطأ والمسؤولية:** 100% على الطرف المتسبب بالدخول.
* **السبب:** عدم إعطاء الأولوية للمركبات المتواجدة داخل الدوار.
                """
            elif "خلف" in desc_lower or "صدم" in desc_lower:
                tech_analysis = """
1. **وضعية المركبات:** المركبة الأمامية كانت تسير بسلامة وفقاً للطريق العام، بينما كانت المركبة الخلفية تلاحقها.
2. **حركة المركبة المتسببة:** المركبة الخلفية لم تترك مسافة كافية للوقوف الآمن ولم تسيطر على المركبة.
3. **نقطة الاصطدام:** اصطدام مقدمة المركبة الخلفية بمؤخرة المركبة الأمامية.
                """
                legal_qualification = """
وفقاً للمذكرة الإيضاحية لنظام المرور ولائحته التنفيذية:
* عدم ترك مسافة أمان كافية بين المركبات.
* عدم السيطرة على المركبة وتوقع الوقوف المفاجئ للمركبة الأمامية.
                """
                official_report = f"""
**موضوع التقرير:** تحديد المسؤولية عن حادث اصطدام من الخلف.

**وصف الحادث:** {accident_desc}

**التحليل الفني والقانوني:** من خلال المعطيات الفنية، تبين أن قائد المركبة الخلفية لم يترك مسافة أمان كافية ولم يتخذ الحيطة والحذر اللازمين للسيطرة على المركبة عند توقف أو تهدئة المركبة الأمامية، مما أدى إلى الاصطدام المباشر بمؤخرة المركبة الأمامية.

**النتيجة النهائية:**
* **نسبة الخطأ والمسؤولية:** 100% على الطرف الثاني (اللاحق).
* **السند النظامي:** قواعد ترك مسافة الأمان والصدم من الخلف.
                """
            else:
                tech_analysis = """
1. **وضعية المركبات:** تم رصد الأطراف ومقاصد الاتجاهات وفقاً لوصف الحادث المدخل.
2. **التحليل الفني:** تقييم حركة السير وأولويات المرور وقت وقوع الاصطدام.
                """
                legal_qualification = """
وفقاً لنظام المرور السعودي ولائحته التنفيذية:
* الالتزام التام بقواعد وأولويات السير العامة والخاصة بالطريق.
                """
                official_report = f"""
**موضوع التقرير:** تقرير تحليل حادث مروري عام.

**وصف الحادث:** {accident_desc}

**التحليل الفني والقانوني:** دراسة المعطيات وتطبيق المواد النظامية ذات العلاقة بتحديد المسؤولية وحجم الخطأ المروري.

**النتيجة النهائية:**
* تحديد المسؤولية بناءً على القواعد المرورية المعتمدة.
                """

            # حفظ التقرير في الجلسة لعرضه وطباعته
            st.session_state['report_ready'] = True
            st.session_state['tech_analysis'] = tech_analysis
            st.session_state['legal_qualification'] = legal_qualification
            st.session_state['official_report'] = official_report

# عرض التقرير إذا كان جاهزاً
if st.session_state.get('report_ready', False):
    st.markdown("---")
    st.markdown("### 📋 التقرير النظامي المفصل للحادث")
    
    st.markdown("---")
    st.markdown("### أولاً: التحليل الفني للحادث")
    st.markdown(st.session_state['tech_analysis'])
    
    st.markdown("---")
    st.markdown("### ثانياً: التكييف النظامي (المخالفة)")
    st.markdown(st.session_state['legal_qualification'])
    
    st.markdown("---")
    st.markdown("### ثالثاً: تقرير الحادث (بصياغة رسمية)")
    st.markdown(st.session_state['official_report'])
    
    st.markdown("---")
    st.caption("ملاحظة: هذا التحليل مبني على الوصف المقدم، وفي الواقع الميداني يتم الاعتماد على تقرير المرور أو نظام نجم بناءً على المعاينة ومواقع التلفيات.")

    # زر الطباعة المباشرة (يحول الصفحة لخيارات الطباعة أو حفظ PDF)
    st.markdown("---")
    print_html = f"""
    <script>
    function printReport() {{
        window.print();
    }}
    </script>
    <button onclick="printReport()" style="
        background-color: #ff4b4b;
        color: white;
        padding: 12px 20px;
        border: none;
        border-radius: 8px;
        font-size: 16px;
        font-weight: bold;
        cursor: pointer;
        width: 100%;">
        🖨️ طباعة التقرير / حفظ كـ PDF
    <//button>
    """
    st.components.v1.html(print_html, height=60)
